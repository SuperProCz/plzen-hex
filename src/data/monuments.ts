import type { FeatureCollection, Point } from "geojson";
import { MONUMENTS_URL } from "../config";

export type MonumentCategory =
  | "hrad"
  | "zamek"
  | "klaster"
  | "tvrz"
  | "kostel"
  | "kaple"
  | "zidovske"
  | "archeologie"
  | "technicke"
  | "sochy"
  | "ostatni";

export interface MonumentProps {
  /** ÚSKP register number (rejstříkové číslo). */
  id: string;
  name: string;
  /** Building/object type, e.g. "městský dům", "kaple". */
  kind: string;
  /** National cultural monument (národní kulturní památka). */
  nkp: boolean;
  category: MonumentCategory;
  /** Municipality (obec) the monument lies in, from RÚIAN. */
  municipality: string | null;
}

export type Monuments = FeatureCollection<Point, MonumentProps>;

/** Generated by scripts/fetch-monuments.mjs from NPÚ open data. */
export async function loadMonuments(): Promise<Monuments> {
  const res = await fetch(MONUMENTS_URL);
  if (!res.ok) throw new Error(`Failed to load monuments: ${res.status}`);
  return res.json();
}
